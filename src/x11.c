			object->vertice=NULL;

			figure[current].vertice=NULL;
			figure[current].xSrc=NULL;
			figure[current].ySrc=NULL;

			// Set [object] [ID] and reset it
			object->ID=current;
			pDebugObjectReset(object);
			pDebugFigureReset(object->ID);

