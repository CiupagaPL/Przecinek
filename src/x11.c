/*
* |\____/| pDebugObjectSetup()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
void pDebugObjectSetup(pObject *object)
{
	// Update [object] [vertexCount] value
	object->vertexCount=figure[object->ID].vertexCount;

	// Check for any [object] [vertex] changes
	if(
		memcmp(
			figure[object->ID].vertex,
			object->vertex,
			sizeof(pPoint)*figure[object->ID].vertexCount
		)
	){
		// Refresh [figure] [vertex] values
		memcpy(
			figure[object->ID].vertex,
			object->vertex,
			sizeof(pPoint)*figure[object->ID].vertexCount
		);

		// Create and setup local [objectMin] and [objectMax]
		pPoint objectMin={ INT_MAX, INT_MAX },
			objectMax={ INT_MIN, INT_MIN };

		for(
			uint16_t current=0;
			current<figure[object->ID].vertexCount;
			current+=1
		){
			// Calculate local [objectMax] values
			if(figure[object->ID].vertex[current].x>objectMax.x)
			{
				objectMax.x=figure[object->ID].vertex[current].x;
			}
			if(figure[object->ID].vertex[current].y>objectMax.y)
			{
				objectMax.y=figure[object->ID].vertex[current].y;
			}

			// Calculate local [objectMin] values
			if(figure[object->ID].vertex[current].x<objectMin.x)
			{
				objectMin.x=figure[object->ID].vertex[current].x;
			}
			if(figure[object->ID].vertex[current].y<objectMin.y)
			{
				objectMin.y=figure[object->ID].vertex[current].y;
			}
		}

		for(
			uint16_t current=0;
			current<figure[object->ID].vertexCount;
			current+=1
		){
			// Calculate [figure] [xSource] and [ySource] values
			figure[object->ID].xSource[current]=
				(float)(objectMax.x-
				figure[object->ID].vertex[current].x)/
				(float)(objectMax.x-objectMin.x);
			figure[object->ID].ySource[current]=
				(float)(objectMax.y-
				figure[object->ID].vertex[current].y)/
				(float)(objectMax.y-objectMin.y);

			figure[object->ID].xSource[current]=
				1.0-figure[object->ID].xSource[current];
			figure[object->ID].ySource[current]=
				1.0-figure[object->ID].ySource[current];
		}

		// Update [figure] size and position parameters
		figure[object->ID].x=objectMin.x;
		figure[object->ID].y=objectMin.y;

		figure[object->ID].width=objectMax.x-objectMin.x;
		figure[object->ID].height=objectMax.y-objectMin.y;
	}

	return;
}

/*
* |\____/| pDebugObjectCross()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
__int128 pDebugObjectCross(
	pPoint *pointA,
	pPoint *pointB,
	pPoint *pointC
){
	// Create and calculate local [ABX] and [ABY]
	__int128 ABX=(__int128)pointB->x-(__int128)pointA->x;
	__int128 ABY=(__int128)pointB->y-(__int128)pointA->y;

	// Create and calculate local [ACX] and [ACY]
	__int128 ACX=(__int128)pointC->x-(__int128)pointA->x;
	__int128 ACY=(__int128)pointC->y-(__int128)pointA->y;

	// Return this little calculation
	return ABX*ACY-ABY*ACX;
}

/*
* |\____/| pDebugObjectCollisionTriangle()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
uint8_t pDebugObjectCollisionTriangle(
	pPoint *A1,
	pPoint *A2,
	pPoint *A3,
	pPoint *B1,
	pPoint *B2,
	pPoint *B3
){
	// Create and setup local [triangle]
	pPoint triangle[2][3]={ { *A1, *A2, *A3 }, { *B1, *B2, *B3 } };

	for(uint8_t current=0; current<6; current+=1)
	{
		// Create local [edge]
		pPoint edge;

		// Calculate local [edge] values
		if(current<3)
		{
			edge.x=
				triangle[0][(current+1)%3].x-
				triangle[0][current].x;
			edge.y=
				triangle[0][(current+1)%3].y-
				triangle[0][current].y;
		}
		else
		{
			edge.x=
				triangle[1][(current-2)%3].x-
				triangle[1][current-3].x;
			edge.y=
				triangle[1][(current-2)%3].y-
				triangle[1][current-3].y;
		}

		// Create local [distanceMin] and [distanceMax]
		pPoint distanceMin={ INT_MAX, INT_MAX },
			distanceMax={ INT_MIN, INT_MIN };

		for(uint8_t loop=0; loop<3; loop+=1)
		{
			// Create local [projection]
			pPoint projection;

			// Caululate local [projection] values
			projection.x=
				(triangle[0][loop].x*-edge.y)+
				(triangle[0][loop].y*edge.x);
			projection.y=
				(triangle[1][loop].x*-edge.y)+
				(triangle[1][loop].y*edge.x);

			// Check for triangular collision
			if(projection.x<distanceMin.x){ distanceMin.x=projection.x; }
			if(projection.x>distanceMax.x){ distanceMax.x=projection.x; }
			if(projection.y<distanceMin.y){ distanceMin.y=projection.y; }
			if(projection.y>distanceMax.y){ distanceMax.y=projection.y; }
		}

		if(distanceMax.x<distanceMin.y || distanceMax.y<distanceMin.x)
		{
			// Return `false`, collision not found
			return false;
		}
	}

	// Return `true`, collision was found
	return true;
}

/*
* |\____/| pDebugObjectInclusive()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
bool pDebugObjectInclusive(
	pPoint *pointA,
	pPoint *pointB,
	pPoint *pointC,
	pPoint *pointD
){
	// Create and check local [checkA], [checkB] and [checkC]
	int8_t checkA=
		(pDebugObjectCross(pointA, pointB, pointD)>0)-
		(pDebugObjectCross(pointA, pointB, pointD)<0);
	int8_t checkB=
		(pDebugObjectCross(pointB, pointC, pointD)>0)-
		(pDebugObjectCross(pointB, pointC, pointD)<0);
	int8_t checkC=
		(pDebugObjectCross(pointC, pointA, pointD)>0)-
		(pDebugObjectCross(pointC, pointA, pointD)<0);

	// Return this overcomplicated thingo
	return !((checkA<0 || checkB<0 || checkC<0) &&
		(checkA>0 || checkB>0 || checkC>0));
}

/*
* |\____/| pObjectCreate()
* |      |
* | o  o |
* \ = .= /
*/
int8_t pObjectCreate(
	pObject *object,
	uint16_t vertexCount
){
	if(!setup)
	{
		printf("pObjectCreate() basic error -1\n");
		printf("przecinek was not set up\n");
		fflush(stdout);

		// Reset [object]
		if(object!=NULL){ pDebugObjectReset(object); }

		// Return `-1`, finished with error
		return -1;
	}
	else if(!object)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -2\n");
			printf("object pointer is NULL\n");
			fflush(stdout);
		}

		// Return `-2`, finished with error
		return -2;
	}

	for(uint16_t current=0; current<OBJECT_MAX; current+=1)
	{
		if(!figure[current].exists)
		{
			// Set some values to `NULL`
			object->vertex=NULL;

			figure[current].vertex=NULL;
			figure[current].xSource=NULL;
			figure[current].ySource=NULL;

			// Set [object] [ID] and reset it
			object->ID=current;
			pDebugObjectReset(object);
			pDebugFigureReset(object->ID);

			// Break current search loop
			break;
		}
		else if(current==OBJECT_MAX-1)
		{
			if(output)
			{
				printf("pObjectCreate() critical error -3\n");
				printf(
					"object limit has been reached (%i)\n",
					OBJECT_MAX
				);
				fflush(stdout);
			}

			// Return `-3`, finished with error
			return -3;
		}
	}

	// Check [vertexCount] value
	if(vertexCount==0)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -4\n");
			printf(
				"[%i] object.vertex could not be allocated\n",
				object->ID
			);
			fflush(stdout);
		}

		// Reset [object] and [figure]
		pDebugObjectReset(object);
		pDebugFigureReset(object->ID);

		// Return `-4`, finished with error
		return -4;
	}
	else if(vertexCount>OBJECT_VERTEX_MAX)
	{
		if(output)
		{
			printf("pObjectCreate() warning\n");
			printf(
				"[%i] object.vertexCount %i->%i\n",
				object->ID,
				vertexCount,
				OBJECT_VERTEX_MAX
			);
			fflush(stdout);
		}

		// Change [vertex] value
		vertexCount=OBJECT_VERTEX_MAX;
	}

	// Allocate [object] [vertex]
	object->vertex=malloc(sizeof(pPoint)*vertexCount);
	if(!object->vertex)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -5\n");
			printf(
				"not enough memory for [%i] object.vertex\n",
				object->ID
			);
			fflush(stdout);
		}

		// Reset [object] and [figure]
		pDebugObjectReset(object);
		pDebugFigureReset(object->ID);

		// Return `-5`, finished with error
		return -5;
	}

	// Set [object] values
	object->vertexCount=vertexCount;
	memset(
		object->vertex,
		0,
		sizeof(pPoint)*vertexCount
	);

	// Allocate [figure] [vertex]
	figure[object->ID].vertex=malloc(sizeof(pPoint)*vertexCount);
	if(!figure[object->ID].vertex)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -6\n");
			printf(
				"not enough memory for [%i] figure.vertex\n",
				object->ID
			);
			fflush(stdout);
		}

		// Reset [object] and [figure]
		pDebugObjectReset(object);
		pDebugFigureReset(object->ID);

		// Return `-6`, finished with error
		return -6;
	}

	// Allocate [figure] [xSource]
	figure[object->ID].xSource=malloc(sizeof(float)*vertexCount);
	if(!figure[object->ID].xSource)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -7\n");
			printf(
				"not enough memory for [%i] figure.xSource\n",
				object->ID
			);
			fflush(stdout);
		}

		// Reset [object] and [figure]
		pDebugObjectReset(object);
		pDebugFigureReset(object->ID);

		// Return `-7`, finished with error
		return -7;
	}

	// Allocate [figure] [ySource]
	figure[object->ID].ySource=malloc(sizeof(float)*vertexCount);
	if(!figure[object->ID].ySource)
	{
		if(output)
		{
			printf("pObjectCreate() critical error -8\n");
			printf(
				"not enough memory for [%i] figure.ySource\n",
				object->ID
			);
			fflush(stdout);
		}

		// Reset [object] and [figure]
		pDebugObjectReset(object);
		pDebugFigureReset(object->ID);

		// Return `-8`, finished with error
		return -8;
	}

	// Set [figure] values
	figure[object->ID].exists=true;

	figure[object->ID].vertexCount=vertexCount;
	memset(
		figure[object->ID].vertex,
		0,
		sizeof(pPoint)*vertexCount
	);

	// Set [figure] [rotationFix] value
	if(vertexCount==4){ figure[object->ID].rotationFix=-45; }
	else{ figure[object->ID].rotationFix=270; }

	// Return `0`, finished succesfully
	return 0;
}

/*
* |\____/| pObjectGenerateShape()
* |      |
* | o  o |
* \ = .= /
*/
int8_t pObjectGenerateShape(
	pObject *object,
	uint16_t width,
	uint16_t height,
	int16_t rotation
){
	if(!object)
	{
		if(output)
		{
			printf("pObjectGenerateShape() critical error -1\n");
			printf("object pointer is NULL\n");
			fflush(stdout);
		}

		// Return `-1`, finished with error
		return -1;
	}
	else if(object->ID>OBJECT_MAX)
	{
		if(output)
		{
			printf("pObjectGenerateShape() critical error -2\n");
			printf("object is corrupted\n");
			fflush(stdout);
		}

		// Return `-2`, finished with error
		return -2;
	}
	else if(!figure[object->ID].exists)
	{
		if(output)
		{
			printf("pObjectGenerateShape() basic error -3\n");
			printf(
				"[%i] object does not exist\n",
				object->ID
			);
			fflush(stdout);
		}

		// Return `-3`, finished with error
		return -3;
	}
	else if(figure[object->ID].vertexCount<3)
	{
		if(output)
		{
			printf("pObjectGenerateShape() basic error -4\n");
			printf(
				"[%i] object.vertexCount should be >=3\n",
				object->ID
			);
			fflush(stdout);
		}

		// Return `-4`, finished with error
		return -4;
	}

	// Check [rotation] value
	if(rotation<OBJECT_ROTATION_MIN)
	{
		if(output)
		{
			printf("pObjectGenerateShape() warning\n");
			printf(
				"[%i] object.rotation %i->%i\n",
				object->ID,
				rotation,
				OBJECT_ROTATION_MIN
			);
			fflush(stdout);
		}

		// Update [rotation] value
		rotation=OBJECT_ROTATION_MIN;
	}
	if(rotation>OBJECT_ROTATION_MAX)
	{
		if(output)
		{
			printf("pObjectGenerateShape() warning\n");
			printf(
				"[%i] object.rotation %i->%i\n",
				object->ID,
				rotation,
				OBJECT_ROTATION_MAX
			);
			fflush(stdout);
		}

		// Update [rotation] value
		rotation=OBJECT_ROTATION_MAX;
	}

	// Create and calculate local [rot]
	float rot=(rotation+figure[object->ID].rotationFix)*M_PI/180.0;

	// Create local [pointX] and [pointY]
	float pointX[figure[object->ID].vertexCount],
		pointY[figure[object->ID].vertexCount];

	// Create and setup local [minX] and [minY]
	float minX=FLT_MAX, minY=FLT_MAX;

	// Create and setup local [maxX] and [maxY]
	float maxX=FLT_MIN, maxY=FLT_MIN;

	for(
		uint16_t current=0;
		current<figure[object->ID].vertexCount;
		current+=1
	){
		// Create and calculate local [angle]
		float angle=
			rot+(2.0*M_PI*current)/
			figure[object->ID].vertexCount;

		// Set local [pointX] and [pointY] values
		pointX[current]=cos(angle);
		pointY[current]=sin(angle);

		// Correct local [minX] and [maxX] values
		if(pointX[current]<minX){ minX=pointX[current]; }
		if(pointX[current]>maxX){ maxX=pointX[current]; }

		// Correct local [minY] and [maxY] values
		if(pointY[current]<minY){ minY=pointY[current]; }
		if(pointY[current]>maxY){ maxY=pointY[current]; }
	}

	// Create and calculate local [scaleX] and [scaleY]
	float scaleX=(float)width/(maxX-minX);
	float scaleY=(float)height/(maxY-minY);

	for(
		uint16_t current=0;
		current<figure[object->ID].vertexCount;
		current+=1
	){
		// Calculate and set [figure] [vertex] values
		figure[object->ID].vertex[current].x=
			round((pointX[current]-minX)*scaleX);
		figure[object->ID].vertex[current].y=
			round((pointY[current]-minY)*scaleY);
	}

	for(
		uint16_t current=0;
		current<figure[object->ID].vertexCount;
		current+=1
	){
		// Calculate [figure] [xSource] and [ySource] values
		figure[object->ID].xSource[current]=
			(float)(width-figure[object->ID].vertex[current].x)/width;
		figure[object->ID].ySource[current]=
			(float)(height-figure[object->ID].vertex[current].y)/height;

		// Correct [figure] [xSource] and [ySource] values
		figure[object->ID].xSource[current]=
			1.0-figure[object->ID].xSource[current];
		figure[object->ID].ySource[current]=
			1.0-figure[object->ID].ySource[current];
	}

	// Copy [figure] [vertex] to the [object]
	memcpy(
		object->vertex,
		figure[object->ID].vertex,
		sizeof(pPoint)*figure[object->ID].vertexCount
	);

	// Update [figure] debug size and position parameters
	figure[object->ID].x=0;
	figure[object->ID].y=0;

	figure[object->ID].width=width;
	figure[object->ID].height=height;

	// Return `0`, finished succesfully
	return 0;
}

