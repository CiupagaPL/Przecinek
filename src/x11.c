/*
* |\____/| pDebugTextSetup()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
int8_t pDebugTextSetup(
	pText *text,
	pFont *font
){
	if(text->size!=code[text->ID].size)
	{
		// Update [code] [size] value
		code[text->ID].size=text->size;

		// Set [code] [change] to `true`
		code[text->ID].change=true;
	}

	// Update [text] [length] value
	text->length=code[text->ID].length;

	// Check [text] [value]
	if(!text->value)
	{
		if(output)
		{
			printf("pDebugTextSetup() warning\n");
			printf(
				"[%i] text.value NULL->%ls\n",
				text->ID,
				code[text->ID].value
			);
			fflush(stdout);
		}

		// Copy [build] [value] to the [text] [value]
		wcscpy(
			text->value,
			code[text->ID].value
		);
	}
	else if(wcscmp(text->value, code[text->ID].value))
	{
		if(wcslen(text->value)>=code[text->ID].length)
		{
			if(output)
			{
				printf("pDebugTextSetup() warning\n");
				printf(
					"[%i] wcslen(text.value) %i->%i\n",
					text->ID,
					(uint16_t)wcslen(text->value),
					code[text->ID].length-1
				);
				fflush(stdout);
			}
		}

		// Copy [text] [value] to the [code] [value]
		wcscpy(
			code[text->ID].value,
			text->value
		);
		// Add [code] and [text] [value] `NULL` terminators
		code[text->ID].value[code[text->ID].length-1]='\0';
		text->value[code[text->ID].length-1]='\0';

		// Set [code] [change] to `true`
		code[text->ID].change=true;
	}

	if(!code[text->ID].change)
	{
		if(
			text->x!=code[text->ID].x[font->ID] ||
			text->y!=code[text->ID].y[font->ID]
		){
			// Create local [diffrence]
			pPoint diffrence=
				(pPoint){
					(text->x-code[0].x[font->ID]),
					(text->y-code[0].y[font->ID])
				};

			for(uint16_t current=0; current<wcslen(text->value); current+=1)
			{
				// Update [code] [sourcePosition] values
				code[text->ID].sourcePosition[font->ID][current].x+=
					diffrence.x;
				code[text->ID].sourcePosition[font->ID][current].y+=
					diffrence.y;
			}

			// Update [code] [x] and [y]
			code[text->ID].x[font->ID]=text->x;
			code[text->ID].y[font->ID]=text->y;
		}

		if(text->letterSpacing!=code[text->ID].letterSpacing)
		{
			// Create local [diffrence]
			int32_t diffrence=
				text->letterSpacing-code[text->ID].letterSpacing;

			for(uint16_t current=0; current<wcslen(text->value); current+=1)
			{
				// Update [code] [sourcePosition] [x] value
				code[text->ID].sourcePosition[font->ID][current].x+=
					diffrence;
			}

			// Update [code] [letterSpacing] value
			code[text->ID].letterSpacing=text->letterSpacing;
		}

		if(text->lineSpacing!=code[text->ID].lineSpacing)
		{
			// Create local [diffrence]
			int32_t diffrence=
				text->lineSpacing-code[text->ID].lineSpacing;

			for(uint16_t current=0; current<wcslen(text->value); current+=1)
			{
				// Update [code] [sourcePosition] [y] value
				code[text->ID].sourcePosition[font->ID][current].y+=
					diffrence;
			}

			// Update [code] [lineSpacing] value
			code[text->ID].lineSpacing=text->lineSpacing;
		}

		if(text->spaceSize!=code[text->ID].spaceSize)
		{
			// Create local [spaceCount] and [yCur]
			uint16_t spaceCount=0;
			int32_t yCur=0;

			// Create local [diffrence]
			int32_t diffrence=
				text->spaceSize-code[text->ID].spaceSize;

			for(uint16_t current=0; current<wcslen(text->value); current+=1)
			{
				if(yCur!=code[text->ID].sourcePosition[font->ID][current].y)
				{
					// Update local [yCur] and reset local [spaceCount]
					yCur=code[text->ID].sourcePosition[font->ID][current].y;
					spaceCount=0;
				}

				// Update [code] [sourcePosition] [x] using local values
				code[text->ID].sourcePosition[font->ID][current].x+=
					spaceCount*diffrence;
			}

			// Update [code] [spaceSize] value
			code[text->ID].spaceSize=text->spaceSize;
		}
	}
	else
	{
		// Update [code] [x] and [y]
		code[text->ID].x[font->ID]=text->x;
		code[text->ID].y[font->ID]=text->y;

		// Update [code] spacing values
		code[text->ID].letterSpacing=text->letterSpacing;
		code[text->ID].lineSpacing=text->lineSpacing;
		code[text->ID].spaceSize=text->spaceSize;
	}

	if(!view[font->ID].created[text->ID] || code[text->ID].change)
	{
		// Set [view] [face] size
		FT_Set_Pixel_Sizes(
			view[font->ID].face,
			0,
			code[text->ID].size
		);

		// Create local [line] and [xFix]
		uint16_t line=0;
		int32_t xFix=0;

		if(view[font->ID].created[text->ID])
		{
			for(uint16_t current=0; current<code[text->ID].length; current+=1)
			{
				// Reset [code] [source] for current [font]
				glDeleteTextures(
					1,
					&code[text->ID].source[font->ID][current]
				);
			}
		}

		for(uint16_t current=0; current<code[text->ID].length; current+=1)
		{
			// Prepare [code] [source] for current [font]
			glGenTextures(
				1,
				&code[text->ID].source[font->ID][current]
			);
		}

		for(
			uint16_t current=0;
			current<wcslen(code[text->ID].value);
			current+=1
		){
			if(code[text->ID].value[current]==L'\n')
			{
				// Reset local [xFix] value
				xFix=0;

				// Increase local [line] value by `1`
				line+=1;

				// Skip special [code] character
				continue;
			}
			else if(code[text->ID].value[current]==L' ')
			{
				// Modify local [xFix] value
				xFix-=code[text->ID].spaceSize;

				// Skip special [code] character
				continue;
			}
			else if(code[text->ID].value[current]==L'\0')
			{
				// Skip special [code] character
				continue;
			}

			// Try to load current char from [code] [value]
			if(
				FT_Load_Char(
					view[text->ID].face,
					code[text->ID].value[current],
					FT_LOAD_RENDER
				) ||
				view[font->ID].face->glyph->bitmap.width==0 ||
				view[font->ID].face->glyph->bitmap.rows==0
			){
				// Skip invalid [code] character
				continue;
			}

			// Create and allocate local [buffer]
			GLubyte* buffer=malloc(
				view[font->ID].face->glyph->bitmap.width*
				view[font->ID].face->glyph->bitmap.rows*4
			);
			if(!buffer)
			{
				if(output)
				{
					printf("pDebugTextSetup() critical error -11\n");
					printf("not enough memory for local buffer\n");
					fflush(stdout);
				}

				// Return `-11`, finished with error
				return -11;
			}

			for(
				uint32_t current=0;
				current<view[font->ID].face->glyph->bitmap.width*
				view[font->ID].face->glyph->bitmap.rows;
				current+=1
			){
				// Create and calculate local [rgba]
				__int128 rgba=current*4;

				// Load [buffer] from [view] [face] [bitmap]
				buffer[rgba]=
					view[font->ID].face->glyph->bitmap.buffer[current];
				buffer[rgba+1]=
					view[font->ID].face->glyph->bitmap.buffer[current];
				buffer[rgba+2]=
					view[font->ID].face->glyph->bitmap.buffer[current];
				buffer[rgba+3]=
					view[font->ID].face->glyph->bitmap.buffer[current];
			}

			// Bind [code] [source]
			glBindTexture(
				GL_TEXTURE_2D,
				code[text->ID].source[font->ID][current]
			);

			// Set `GL_UNPACK_ALIGNMENT` value to `1`
			glPixelStorei(GL_UNPACK_ALIGNMENT, 1);

			// Convert local [buffer] to the [code] [source]
			glTexImage2D(
				GL_TEXTURE_2D,
				0,
				GL_RGBA,
				view[font->ID].face->glyph->bitmap.width,
				view[font->ID].face->glyph->bitmap.rows,
				0,
				GL_RGBA,
				GL_UNSIGNED_BYTE,
				buffer
			);

			// Setup `GL_TEXTURE_FILTER`
			glTexParameteri(
				GL_TEXTURE_2D,
				GL_TEXTURE_MIN_FILTER,
				GL_LINEAR
			);
			glTexParameteri(
				GL_TEXTURE_2D,
				GL_TEXTURE_MAG_FILTER,
				GL_LINEAR
			);

			// Set [code] [sourceSize] values
			code[text->ID].sourceSize[font->ID][current].width=
				view[font->ID].face->glyph->metrics.width>>6;
			code[text->ID].sourceSize[font->ID][current].height=
				view[font->ID].face->glyph->metrics.height>>6;

			// Set [code] [sourcePosition] values
			code[text->ID].sourcePosition[font->ID][current].x=
				code[text->ID].x[font->ID]-xFix;
			code[text->ID].sourcePosition[font->ID][current].y=
				code[text->ID].y[font->ID]-
				view[font->ID].face->glyph->bitmap_top+
				((code[text->ID].size*458)/512)+
				((view[font->ID].face->size->metrics.height>>6)*line)+
				(code[text->ID].lineSpacing*line);

			// Change local [xFix] value
			xFix-=
				code[text->ID].sourceSize[font->ID][current].width+
				code[text->ID].letterSpacing;

			// Clean up
			free(buffer);
		}

		// Set [view] [created] to `true`
		view[font->ID].created[text->ID]=true;

		// Set [code] [change] to `false`
		code[text->ID].change=false;
	}

	// Return `0`, finished succesfully
	return 0;
}

/*
* |\____/| pTextCreate()
* |      |
* | o  o |
* \ = .= /
*/
int8_t pTextCreate(
	pText *text,
	uint16_t length
){
	if(!setup)
	{
		printf("pTextCreate() basic error -1\n");
		printf("przecinek was not set up\n");
		fflush(stdout);

		// Reset [text]
		if(text!=NULL){ pDebugTextReset(text); }

		// Return `-1`, finished with error
		return -1;
	}
	else if(!text)
	{
		if(output)
		{
			printf("pTextCreate() critical error -2\n");
			printf("text pointer is NULL\n");
			fflush(stdout);
		}

		// Return `-2`, finished with error
		return -2;
	}

	for(uint16_t current=0; current<TEXT_MAX; current+=1)
	{
		if(!code[current].exists)
		{
			// Set some values to `NULL`
			text->value=NULL;

			code[current].value=NULL;

			// Set [text] [ID] and reset it
			text->ID=current;
			pDebugTextReset(text);
			pDebugCodeReset(text->ID);

			// Break current search loop
			break;
		}
		else if(current==TEXT_MAX-1)
		{
			if(output)
			{
				printf("pTextCreate() critical error -3\n");
				printf(
					"text limit has been reached (%i)\n",
					TEXT_MAX
				);
				fflush(stdout);

			}

			// Return `-3`, finished with error
			return -3;
		}
	}

	// Check [length] value
	if(length==0)
	{
		if(output)
		{
			printf("pTextCreate() critical error -4\n");
			printf(
				"[%i] text.value could not be allocated\n",
				text->ID
			);
			fflush(stdout);
		}

		// Reset [text] and [code]
		pDebugTextReset(text);
		pDebugCodeReset(text->ID);

		// Return `-4`, finished with error
		return -4;
	}

	// Allocate [text] [value]
	text->value=malloc(sizeof(wchar_t)*length);
	if(!text->value)
	{
		if(output)
		{
			printf("pTextCreate() critical error -5\n");
			printf(
				"not enough memory for [%i] text.value\n",
				text->ID
			);
			fflush(stdout);
		}

		// Reset [text] and [code]
		pDebugTextReset(text);
		pDebugCodeReset(text->ID);

		// Return `-5`, finished with error
		return -5;
	}

	// Set [text] values
	text->length=length;
	text->size=TEXT_SIZE_DEFAULT;

	text->letterSpacing=0;
	text->lineSpacing=0;
	text->spaceSize=TEXT_SPACE_SIZE_DEFAULT;

	// Allocate [code] [value]
	code[text->ID].value=malloc(sizeof(wchar_t)*length);
	if(!code[text->ID].value)
	{
		if(output)
		{
			printf("pTextCreate() critical error -6\n");
			printf(
				"not enough memory for [%i] code.value\n",
				text->ID
			);
			fflush(stdout);
		}

		// Reset [text] and [code]
		pDebugTextReset(text);
		pDebugCodeReset(text->ID);

		// Return `-6`, finished with error
		return -6;
	}

	// Add `NULL` terminator to the [code] [value]
	code[text->ID].value[text->length-1]='\0';

	for(uint16_t current=0; current<FONT_MAX; current+=1)
	{
		// Allocate [code] [source]
		code[text->ID].source[current]=malloc(sizeof(GLuint)*length);
		if(!code[text->ID].source[current])
		{
			if(output)
			{
				printf("pTextCreate() critical error -7\n");
				printf(
					"not enough memory for [%i] code.source\n",
					text->ID
				);
				fflush(stdout);
			}

			// Return `-7`, finished with error
			return -7;
		}

		// Allocate [code] [sourceSize]
		code[text->ID].sourceSize[current]=malloc(sizeof(pSize)*length);
		if(!code[text->ID].sourceSize[current])
		{
			if(output)
			{
				printf("pTextCreate() critical error -8\n");
				printf(
					"not enough memory for [%i] code.sourceSize\n",
					text->ID
				);
				fflush(stdout);
			}

			// Return `-8`, finished with error
			return -8;
		}

		// Allocate [code] [sourcePosition]
		code[text->ID].sourcePosition[current]=malloc(sizeof(pPoint)*length);
		if(!code[text->ID].sourcePosition[current])
		{
			if(output)
			{
				printf("pTextCreate() critical error -9\n");
				printf(
					"not enough memory for [%i] code.sourcePosition\n",
					text->ID
				);
				fflush(stdout);
			}

			// Return `-9`, finished with error
			return -9;
		}
	}

	// Set [code] values
	code[text->ID].exists=true;

	code[text->ID].length=length;

	code[text->ID].letterSpacing=TEXT_LETTER_SPACING_DEFAULT;
	code[text->ID].lineSpacing=TEXT_LINE_SPACING_DEFAULT;
	code[text->ID].spaceSize=TEXT_SPACE_SIZE_DEFAULT;

	// Return `0`, finished succesfully
	return 0;
}

