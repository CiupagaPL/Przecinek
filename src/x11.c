/*
* |\____/| pSetup()
* |      |
* | o  o |
* \ = .= /
*/
int8_t pSetup(bool debug)
{
	if(setup)
	{
		if(debug)
		{
			printf("pSetup() basic error -1\n");
			printf("przecinek was already set up\n");
			fflush(stdout);
		}

		// Return `-1`, finished with error
		return -1;
	}

	// Initialize locale; use default for `LC_ALL`
	setlocale(LC_ALL, "");

	// Set [output] value
	output=debug;

	// Set [przecinek] [frameLimit] initial value
	przecinek.frameLimit=PRZECINEK_FRAME_DEFAULT;

	// Try to initialize [freeType] library and variable
	if(FT_Init_FreeType(&freeType))
	{
		if(output)
		{
			printf("pSetup() critical error -2\n");
			printf("FreeType2 library does not work\n");
			fflush(stdout);
		}

		// Return `-2`, finished with error
		return -2;
	}

	// Try to initialize empty [display]
	display=XOpenDisplay(NULL);
	if(!display)
	{
		if(output)
		{
			printf("pSetup() critical error -3\n");
			printf("X11 display does not work\n");
			fflush(stdout);
		}

		// Return `-3`, finished with error
		return -3;
	}

	// Set [przecinek] [display] values
	przecinek.display.width=
		XDisplayWidth(
			display,
			DefaultScreen(display)
		);
	przecinek.display.height=
		XDisplayHeight(
			display,
			DefaultScreen(display)
		);

	// Create local [cursorMainX] and [cursorMainY]
	int cursorMainX, cursorMainY;
	// Create local [cursorLocalX] and [cursorLocalY]
	int cursorLocalX, cursorLocalY;
	// Create local [mask] and [windowDump]
	unsigned int mask;
	Window windowDump;

	// Load cursor position on the [display]
	if(
		XQueryPointer(
			display,
			DefaultRootWindow(display),
			&windowDump,
			&windowDump,
			&cursorMainX,
			&cursorMainY,
			&cursorLocalX,
			&cursorLocalY,
			&mask
		)
	){
		// Set [przecinek] [cursor] values
		przecinek.cursor.x=cursorMainX;
		przecinek.cursor.y=cursorMainY;
	}
	else
	{
		if(output)
		{
			printf("pSetup() warning\n");
			printf("X11 mouse position is broken\n");
			fflush(stdout);
		}

		// Reset [przecinek] [cursor] values
		przecinek.cursor.x=0;
		przecinek.cursor.y=0;
	}

	// Create local [count]
	int32_t count;

	// Create and load local [visual] from GLX
	XVisualInfo *visual=
		glXGetVisualFromFBConfig(
			display,
			glXGetFBConfigs(
				display,
				DefaultScreen(display),
				&count
			)[0]
		);

	// Initialize GLX [buffer]
	buffer=
		glXCreateContext(
			display,
			visual,
			NULL,
			GL_TRUE
		);

	for(uint8_t ID=0; ID<WINDOW_MAX; ID+=1)
	{
		// Set [build] [exists] to `false`
		build[ID].exists=false;
	}
	for(uint16_t ID=0; ID<OBJECT_MAX; ID+=1)
	{
		// Set [figure] [exists] to `false`
		figure[ID].exists=false;
	}
	for(uint16_t ID=0; ID<FONT_MAX; ID+=1)
	{
		// Set [view] [exists] to `false`
		view[ID].exists=false;
	}
	for(uint16_t ID=0; ID<TEXT_MAX; ID+=1)
	{
		// Set [code] [exists] to `false`
		code[ID].exists=false;
	}
	for(uint16_t ID=0; ID<IMAGE_MAX; ID+=1)
	{
		// Set [texture] [exists] to `false`
		texture[ID].exists=false;
	}
	for(uint16_t ID=0; ID<AUDIO_MAX; ID+=1)
	{
		// Set [sound] [exists] to `false`
		sound[ID].exists=false;
	}

	// Get [frameStart] initial time value
	gettimeofday(&frameStart, NULL);

	// Set [setup] to `true`
	setup=true;

	// Return `0`, finished succesfully
	return 0;
}

/*
* |\____/| pUpdate()
* |      |
* | o  o |
* \ = .= /
*/
int8_t pUpdate()
{
	if(!setup)
	{
		printf("pUpdate() basic error -1\n");
		printf("przecinek was not set up\n");
		fflush(stdout);

		// Return `-1`, finished with error
		return -1;
	}

	// Check if [windowMainID] [exists]
	if(!build[windowMainID].exists && windowCount!=0)
	{
		for(uint8_t current=0; current<WINDOW_MAX; current+=1)
		{
			if(build[windowMainID].exists)
			{
				// Update [windowMainID] value
				windowMainID=current;

				// Exit loop
				break;
			}
		}
	}

	for(uint8_t button=0; button<PRZECINEK_KEY_PRESS_MAX; button+=1)
	{
		if(keyboard[input[button]]==1){
			// Set current [keyboard] to `2`
			keyboard[input[button]]=2;
		}
	}

	// Check [przecinek] [frameLimit] value
	if(przecinek.frameLimit<PRZECINEK_FRAME_MIN)
	{
		if(output)
		{
			printf("pUpdate() warning\n");
			printf(
				"przecinek.frameLimit %i->%i\n",
				przecinek.frameLimit,
				PRZECINEK_FRAME_MIN
			);
			fflush(stdout);
		}

		// Update [przecinek] [frameLimit] value
		przecinek.frameLimit=PRZECINEK_FRAME_MIN;
	}
	else if(przecinek.frameLimit>PRZECINEK_FRAME_MAX)
	{
		if(output)
		{
			printf("pUpdate() warning\n");
			printf(
				"przecinek.frameLimit %i->%i\n",
				przecinek.frameLimit,
				PRZECINEK_FRAME_MAX
			);
			fflush(stdout);
		}

		// Update [przecinek] [frameLimit] value
		przecinek.frameLimit=PRZECINEK_FRAME_MAX;
	}

	if(lastFrame!=przecinek.frameLimit)
	{
		// Update [lastFrame] value
		lastFrame=przecinek.frameLimit;

		// Update [currentFrameLimit] value
		currentFrameLimit=przecinek.frameLimit;
	}

	// Update [przecinek] [display] values
	przecinek.display.width=
		DisplayWidth(
			display,
			DefaultScreen(display)
		);
	przecinek.display.height=
		DisplayHeight(
			display,
			DefaultScreen(display)
		);

	// Create local [cursorMainX] and [cursorMainY]
	int cursorMainX, cursorMainY;
	// Create local [cursorLocalX] and [cursorLocalY]
	int cursorLocalX, cursorLocalY;
	// Create local [mask] and [windowDump]
	unsigned int mask;
	Window windowDump;

	// Load cursor position on the [display]
	if(
		XQueryPointer(
			display,
			DefaultRootWindow(display),
			&windowDump,
			&windowDump,
			&cursorMainX,
			&cursorMainY,
			&cursorLocalX,
			&cursorLocalY,
			&mask
		)
	){
		// Update [przecinek] [cursor] values
		przecinek.cursor.x=cursorMainX;
		przecinek.cursor.y=cursorMainY;
	}
	else
	{
		if(output)
		{
			printf("pUpdate() warning\n");
			printf("X11 mouse position is broken\n");
			fflush(stdout);
		}

		// Reset [przecinek] [cursor] values
		przecinek.cursor.x=0;
		przecinek.cursor.y=0;
	}

	for(uint16_t ID=0; ID<WINDOW_MAX; ID+=1)
	{
		if(build[ID].exists)
		{
			// Handle current [build] update
			pDebugWindowHandle(ID);
		}
	}

	// Increase [frameCount] by `1`
	frameCount+=1;

	// Sleep for a short amount of time
	usleep(1000000/currentFrameLimit);

	// Create local [frameCurrent] structure
	struct timeval frameCurrent;
	// Get local [frameCurrent] initial time value
	gettimeofday(&frameCurrent, NULL);

	// Create local [frameOverhead]
	int16_t frameOverhead=0;

	// Create and calculcate local [frameTime]
	double frameTime=
		(frameCurrent.tv_sec-frameStart.tv_sec)+
		(double)(frameCurrent.tv_usec-frameStart.tv_usec)/1000000.0;

	if(frameTime<1.0 && frameCount>=przecinek.frameLimit+3)
	{
		// Set local [frameOverhead] value to `1`
		frameOverhead=1;
	}
	else if(frameTime>=1.0 && frameCount<przecinek.frameLimit-5)
	{
		// Calculate local [frameOverhead] value
		frameOverhead=frameCount-przecinek.frameLimit;
	}

	if(frameTime>=1.0)
	{
		// Update [lastFrameCount] value
		lastFrameCount=frameCount;

		// Reset [frameCount] and update [frameStart] time value
		frameCount=0;
		gettimeofday(&frameStart, NULL);

		// Update [currentFrameLimit] value
		currentFrameLimit-=frameOverhead;

		if(currentFrameLimit>=przecinek.frameLimit*3)
		{
			// Correct [currentFrameLimit] value
			currentFrameLimit=przecinek.frameLimit*3;
		}
	}

	// Update [przecinek] [frameCount] value
	przecinek.frameCount=lastFrameCount;

	// Refresh console
	fflush(stdout);

	// Return `0`, finished succesfully
	return 0;
}

