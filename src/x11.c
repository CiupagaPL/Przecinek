/*
* |\____/| pObjectGenerate()
* |      |
* | o  o | In: pObject* [object], uint16_t [width], [height], int16_t [rotation]
* \ = .= / Out: int8_t (`0`: success)
*
* > Parameters:
* [object] - which [object] structure should be generated.
* [width], [height] - how big should the [object] be.
* [rotation] - how rotated should the [object] be.
*
* > Description:
* This function generates [object] structure based on given parameters.
* It automatically calculates [vertice] positions and creates geometric figure.
* It also prepares debug values like [texture] positions and [object] [width] and [height].
*/
int8_t pObjectGenerate(pObject *object, uint16_t width, uint16_t height, int16_t rotation){
	if(object==NULL){
		if(output==true){
			printf("[pObjectGenerate() Error]\n");
			printf("Given object is `NULL`!\n");
			printf("Make sure to use your brain once in a while,\n");
			fflush(stdout);
		}

		// Return `-1`, finished with error
		return -1;
	}
	else if(object->ID>OBJECT_MAX){
		if(output==true){
			printf("[pObjectGenerate() Error]\n");
			printf("Given object was not created properly!\n");
			printf("Value of the object.ID is out of range.\n");
			printf("Try to not use corrupted variables next time,\n");
			fflush(stdout);
		}

		// Return `-2`, finished with error
		return -2;
	}
	else if(figure[object->ID].exists==false){
		if(output==true){
			printf("[pObjectGenerate() Error]\n");
			printf("Given object is already destroyed!\n");
			printf("Not sure what you were trying todo :-PP,\n");
			fflush(stdout);
		}

		// Return `-3`, finished with error
		return -3;
	}

	// Check [rotation] value
	if(rotation<OBJECT_ROTATION_MIN){
		if(output==true){
			printf("[pObjectGenerate() Warning]\n");
			printf("Value of the object.rotation is too small!\n");
			printf(
				"Value of the object.rotation was changed from %i to %i,\n",
				rotation, OBJECT_ROTATION_MIN
			);
			fflush(stdout);
		}

		// Update [rotation] value
		rotation=OBJECT_ROTATION_MIN;
	}
	if(rotation>OBJECT_ROTATION_MAX){
		if(output==true){
			printf("[pObjectGenerate() Warning]\n");
			printf("Value of the object.rotation is too large!\n");
			printf(
				"Value of the object.rotation was changed from %i to %i,\n",
				rotation, OBJECT_ROTATION_MAX
			);
			fflush(stdout);
		}

		// Update [rotation] value
		rotation=OBJECT_ROTATION_MAX;
	}

	// Create and calculate local [rot]
	float rot=(rotation+figure[object->ID].rotationFix)*M_PI/180.0;

	// Create local [pointX] and [pointY]
	float pointX[figure[object->ID].verticeCount], pointY[figure[object->ID].verticeCount];

	// Create and setup local [minX] and [minY]
	float minX=FLT_MAX, minY=FLT_MAX;

	// Create and setup local [maxX] and [maxY]
	float maxX=FLT_MIN, maxY=FLT_MIN;

	for(uint16_t current=0; current<figure[object->ID].verticeCount; current+=1){
		// Create and calculate local [angle]
		float angle=rot+(2.0*M_PI*current)/figure[object->ID].verticeCount;

		// Set local [pointX] and [pointY] values
		pointX[current]=cos(angle);
		pointY[current]=sin(angle);

		// Correct local [minX] and [maxX] values
		if(pointX[current]<minX){ minX=pointX[current]; }
		if(pointX[current]>maxX){ maxX=pointX[current]; }

		// Correct local [minY] and [maxY] values
		if(pointY[current]<minY){ minY=pointY[current]; }
		if(pointY[current]>maxY){ maxY=pointY[current]; }
	}

	// Create and calculate local [scaleX] and [scaleY]
	float scaleX=(float)width/(maxX-minX);
	float scaleY=(float)height/(maxY-minY);

	for(uint16_t current=0; current<figure[object->ID].verticeCount; current+=1){
		// Calculate and set [figure] [vertice] values
		figure[object->ID].vertice[current].x=round((pointX[current]-minX)*scaleX);
		figure[object->ID].vertice[current].y=round((pointY[current]-minY)*scaleY);
	}

	for(uint16_t current=0; current<figure[object->ID].verticeCount; current+=1){
		// Calculate [figure] [xSrc] and [ySrc] values
		figure[object->ID].xSrc[current]=
			(float)(width-figure[object->ID].vertice[current].x)/width;
		figure[object->ID].ySrc[current]=
			(float)(height-figure[object->ID].vertice[current].y)/height;

		// Correct [figure] [xSrc] and [ySrc] values
		figure[object->ID].xSrc[current]=1.0-figure[object->ID].xSrc[current];
		figure[object->ID].ySrc[current]=1.0-figure[object->ID].ySrc[current];
	}

	// Copy [figure] [vertice] to the [object]
	memcpy(
		object->vertice, figure[object->ID].vertice,
		sizeof(pPoint)*figure[object->ID].verticeCount
	);

	// Update [figure] debug size and position parameters
	figure[object->ID].x=0;
	figure[object->ID].y=0;

	figure[object->ID].width=width;
	figure[object->ID].height=height;

	// Return `0`, finished succesfully
	return 0;
}

