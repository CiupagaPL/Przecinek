/*
* |\____/| pDebugObjectSetup()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
void pDebugObjectSetup(pObject *object){
	// Update [object] [verticeCount]
	object->verticeCount=figure[object->ID].verticeCount;

	// Check for any [object] [vertice] changes
	if(memcmp(figure[object->ID].vertice, object->vertice,
			sizeof(pPoint)*figure[object->ID].verticeCount)!=0){

		// Refresh [figure] [vertice] values
		memcpy(
			figure[object->ID].vertice, object->vertice,
			sizeof(pPoint)*figure[object->ID].verticeCount
		);

		// Create and setup local [objectMin] and [objectMax]
		pPoint objectMin={ INT_MAX, INT_MAX }, objectMax={ INT_MIN, INT_MIN };

		for(uint16_t current=0; current<figure[object->ID].verticeCount; current+=1){
			// Calculate local [objectMax] values
			if(figure[object->ID].vertice[current].x>objectMax.x){
				objectMax.x=figure[object->ID].vertice[current].x;
			}
			if(figure[object->ID].vertice[current].y>objectMax.y){
				objectMax.y=figure[object->ID].vertice[current].y;
			}

			// Calculate local [objectMin] values
			if(figure[object->ID].vertice[current].x<objectMin.x){
				objectMin.x=figure[object->ID].vertice[current].x;
			}
			if(figure[object->ID].vertice[current].y<objectMin.y){
				objectMin.y=figure[object->ID].vertice[current].y;
			}
		}

		for(uint16_t current=0; current<figure[object->ID].verticeCount; current+=1){
			// Calculate [figure] [xSrc] and [ySrc] values
			figure[object->ID].xSrc[current]=
				(float)(objectMax.x-figure[object->ID].vertice[current].x)/
				(float)(objectMax.x-objectMin.x);
			figure[object->ID].ySrc[current]=
				(float)(objectMax.y-figure[object->ID].vertice[current].y)/
				(float)(objectMax.y-objectMin.y);

			figure[object->ID].xSrc[current]=1.0-figure[object->ID].xSrc[current];
			figure[object->ID].ySrc[current]=1.0-figure[object->ID].ySrc[current];
		}

		// Update [figure] size and position parameters
		figure[object->ID].x=objectMin.x;
		figure[object->ID].y=objectMin.y;

		figure[object->ID].width=objectMax.x-objectMin.x;
		figure[object->ID].height=objectMax.y-objectMin.y;
	}

	return;
}

/*
* |\____/| pDebugObjectCross()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
__int128 pDebugObjectCross(pPoint *pointA, pPoint *pointB, pPoint *pointC){
	// Create and calculate local [ABX] and [ABY]
	__int128 ABX=(__int128)pointB->x-(__int128)pointA->x;
	__int128 ABY=(__int128)pointB->y-(__int128)pointA->y;

	// Create and calculate local [ACX] and [ACY]
	__int128 ACX=(__int128)pointC->x-(__int128)pointA->x;
	__int128 ACY=(__int128)pointC->y-(__int128)pointA->y;

	// Return this little calculation
	return ABX*ACY-ABY*ACX;
}

/*
* |\____/| pDebugObjectCollisionTriangle()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
uint8_t pDebugObjectCollisionTriangle(
	pPoint *A1, pPoint *A2, pPoint *A3,
	pPoint *B1, pPoint *B2, pPoint *B3
){

	// Create and setup local [triangle]
	pPoint triangle[2][3]={ { *A1, *A2, *A3 }, { *B1, *B2, *B3 } };

	for(uint8_t current=0; current<6; current+=1){
		// Create local [edge]
		pPoint edge;

		// Calculate local [edge] values
		if(current<3){
			edge.x=triangle[0][(current+1)%3].x-triangle[0][current].x;
			edge.y=triangle[0][(current+1)%3].y-triangle[0][current].y;
		}
		else{
			edge.x=triangle[1][(current-2)%3].x-triangle[1][current-3].x;
			edge.y=triangle[1][(current-2)%3].y-triangle[1][current-3].y;
		}

		// Create local [distanceMin] and [distanceMax]
		pPoint distanceMin={ INT_MAX, INT_MAX }, distanceMax={ INT_MIN, INT_MIN };

		for(uint8_t loop=0; loop<3; loop+=1){
			// Create local [projection]
			pPoint projection;

			// Caululate local [projection] values
			projection.x=(triangle[0][loop].x*-edge.y)+(triangle[0][loop].y*edge.x);
			projection.y=(triangle[1][loop].x*-edge.y)+(triangle[1][loop].y*edge.x);

			// Check for collision
			if(projection.x<distanceMin.x){ distanceMin.x=projection.x; }
			if(projection.x>distanceMax.x){ distanceMax.x=projection.x; }
			if(projection.y<distanceMin.y){ distanceMin.y=projection.y; }
			if(projection.y>distanceMax.y){ distanceMax.y=projection.y; }
		}

		if(distanceMax.x<distanceMin.y || distanceMax.y<distanceMin.x){
			// Return `false`, collision not found
			return false;
		}
	}

	// Return `true`, collision was found
	return true;
}

/*
* |\____/| pDebugObjectInclusive()
* |      |
* | o  o | [DEBUG]
* \ = .= /
*/
bool pDebugObjectInclusive(pPoint *pointA, pPoint *pointB, pPoint *pointC, pPoint *pointD){
	// Create and check local [checkA], [checkB] and [checkC]
	int8_t checkA=(pDebugObjectCross(pointA, pointB, pointD)>0)-
		(pDebugObjectCross(pointA, pointB, pointD)<0);
	int8_t checkB=(pDebugObjectCross(pointB, pointC, pointD)>0)-
		(pDebugObjectCross(pointB, pointC, pointD)<0);
	int8_t checkC=(pDebugObjectCross(pointC, pointA, pointD)>0)-
		(pDebugObjectCross(pointC, pointA, pointD)<0);

	// Return this overcomplicated thing
	return ((checkA<0 || checkB<0 || checkC<0) && (checkA>0 || checkB>0 || checkC>0))==false;
}

